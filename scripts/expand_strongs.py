NT_BOOKS = {
    'Matthew', 'Mark', 'Luke', 'John', 'Acts', 'Romans', '1 Corinthians', '2 Corinthians',
    'Galatians', 'Ephesians', 'Philippians', 'Colossians', '1 Thessalonians', '2 Thessalonians',
    '1 Timothy', '2 Timothy', 'Titus', 'Philemon', 'Hebrews', 'James', '1 Peter', '2 Peter',
    '1 John', '2 John', '3 John', 'Jude', 'Revelation'
}

total_added = 0

for book in kjv['books']:
    is_nt = book['name'] in NT_BOOKS
    dict_map = GREEK_ADDITIONS if is_nt else HEBREW_ADDITIONS
    
    for chap in book['chapters']:
        for v in chap['verses']:
            st = v.get('strongsText', '')
            for w, tag in dict_map.items():
                pattern = rf'\b({w})\b(?!\[[HG]\d+\])'
                def repl(m):
                    global total_added
                    total_added += 1
                    return f'{m.group(1)}[{tag}]'
                st = re.sub(pattern, repl, st, flags=re.IGNORECASE)
            
            # Clean up double brackets or orphan tags
            v['strongsText'] = st

print(f'Successfully added {total_added} additional Strongs mappings!')

with open('public/kjv.json', 'w', encoding='utf-8') as f:
    json.dump(kjv, f, separators=(',', ':'), ensure_ascii=False)

